/** @vitest-environment jsdom */
import { cleanup, fireEvent, render, screen } from '@testing-library/react';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import CgmImport from '../CgmImport';
import { toLocalISO } from '../../domain/time';

const DICT = {
  importCgmTitre: 'Importer un capteur (CSV)',
  importCgmDesc: 'Fichiers LibreView ou Dexcom.',
  importCgmChoisir: 'Choisir un fichier CSV',
  importCgmResultat: '{added} lectures importées, {duplicates} doublons ignorés, {skipped} lignes ignorées.',
  importCgmFormat: 'Format détecté : {format}',
  importCgmErreur: 'Fichier non reconnu.',
};

const t = (key, params) => {
  let msg = DICT[key] || key;
  if (params) Object.entries(params).forEach(([k, v]) => { msg = msg.replace(`{${k}}`, v); });
  return msg;
};

const LIBRE_HEADER = [
  'Device', 'Serial Number', 'Device Timestamp', 'Record Type', 'Historic Glucose mg/dL', 'Scan Glucose mg/dL',
  'Non-numeric Rapid-Acting Insulin', 'Rapid-Acting Insulin (units)', 'Non-numeric Food', 'Carbohydrates (grams)',
  'Carbohydrates (servings)', 'Non-numeric Long-Acting Insulin', 'Long-Acting Insulin (units)', 'Notes',
  'Strip Glucose mg/dL', 'Ketone mmol/L', 'Meal Insulin (units)', 'Correction Insulin (units)', 'User Change Insulin (units)',
].join(',');

function libreRow(ts, type, cells = {}) {
  const row = Array(19).fill('');
  row[0] = 'FreeStyle LibreLink';
  row[1] = 'ABC123';
  row[2] = ts;
  row[3] = type;
  for (const [idx, value] of Object.entries(cells)) row[Number(idx)] = value;
  return row.join(',');
}

const LIBRE_CSV = [
  'Glucose Data,Generated on 11-10-2026 10:00 UTC,Generated by FreeStyle LibreLink',
  'Patient Report,Jane Doe,Generated on 11-10-2026 10:00 UTC',
  LIBRE_HEADER,
  libreRow('11-10-2026 08:15', '0', { 4: '120' }),
  libreRow('11-10-2026 08:30', '0', { 4: '135' }),
  libreRow('11-10-2026 08:20', '1', { 5: '128' }),
  libreRow('11-10-2026 09:00', '4', { 11: 'Long-Acting', 12: '12' }),
  libreRow('not a date', '0', { 4: '100' }),
].join('\n');

const makeFile = (content) => new File([content], 'glucose.csv', { type: 'text/csv' });

describe('CgmImport', () => {
  let onImport;

  beforeEach(() => {
    onImport = vi.fn();
  });

  afterEach(cleanup);

  it('rend le titre, la description et un champ fichier CSV', () => {
    render(<CgmImport journal={[]} onImport={onImport} t={t} isDark={false} />);
    expect(screen.getByRole('heading', { name: 'Importer un capteur (CSV)' })).toBeTruthy();
    expect(screen.getByText('Fichiers LibreView ou Dexcom.')).toBeTruthy();
    const input = screen.getByLabelText('Choisir un fichier CSV');
    expect(input.type).toBe('file');
    expect(input.accept).toBe('.csv,text/csv');
  });

  it('importe un CSV LibreView en entrées de source cgm', async () => {
    render(<CgmImport journal={[]} onImport={onImport} t={t} isDark={false} />);

    fireEvent.change(screen.getByLabelText('Choisir un fichier CSV'), { target: { files: [makeFile(LIBRE_CSV)] } });

    const status = await screen.findByRole('status');
    expect(status.textContent).toContain('Format détecté : LibreView');
    expect(status.textContent).toContain('3 lectures importées, 0 doublons ignorés, 1 lignes ignorées.');

    expect(onImport).toHaveBeenCalledTimes(1);
    const entries = onImport.mock.calls[0][0];
    expect(entries).toHaveLength(3);
    for (const entry of entries) {
      expect(entry.source).toBe('cgm');
      expect(entry.mealType).toBe('mesure');
      expect(typeof entry.id).toBe('string');
      expect(typeof entry.glycPre).toBe('number');
    }
    expect(entries.map((e) => e.glycPre)).toEqual([1.2, 1.28, 1.35]);
    expect(entries[0].date).toBe(toLocalISO(new Date(2026, 9, 11, 8, 15)));
  });

  it('écarte les lectures déjà présentes dans le journal', async () => {
    const existing = [{ id: 'cgm_x', date: toLocalISO(new Date(2026, 9, 11, 8, 15)), glycPre: 1.2, source: 'cgm', mealType: 'mesure' }];
    render(<CgmImport journal={existing} onImport={onImport} t={t} isDark />);

    fireEvent.change(screen.getByLabelText('Choisir un fichier CSV'), { target: { files: [makeFile(LIBRE_CSV)] } });

    const status = await screen.findByRole('status');
    expect(status.textContent).toContain('2 lectures importées, 1 doublons ignorés, 1 lignes ignorées.');
    expect(onImport.mock.calls[0][0]).toHaveLength(2);
  });

  it('affiche une alerte pour un fichier non reconnu', async () => {
    render(<CgmImport journal={[]} onImport={onImport} t={t} isDark={false} />);

    fireEvent.change(screen.getByLabelText('Choisir un fichier CSV'), { target: { files: [makeFile('garbage\nmore garbage')] } });

    const alert = await screen.findByRole('alert');
    expect(alert.textContent).toBe('Fichier non reconnu.');
    expect(onImport).not.toHaveBeenCalled();
    expect(screen.queryByRole('status')).toBeNull();
  });
});
