// ─── parseCgmCsv ────────────────────────────────────────────────────────────

describe('parseCgmCsv — LibreView', () => {
  it('lit un export européen (DMY) avec préambule, historique, scan et bandelette', () => {
    const res = parseCgmCsv(LIBRE_DMY);
    expect(res.format).toBe('libreview');
    expect(res.unit).toBe('mg/dL');
    expect(res.errors).toEqual([]);
    expect(res.skipped).toBe(2); // date illisible + valeur vide
    expect(summary(res.readings)).toEqual([
      [new Date(2026, 9, 11, 8, 15), 1.2, 'historic'],
      [new Date(2026, 9, 11, 8, 20), 1.28, 'scan'],
      [new Date(2026, 9, 11, 8, 30), 1.35, 'historic'],
      [new Date(2026, 9, 11, 8, 45), 1.42, 'manual'],
      [new Date(2026, 9, 25, 8, 0), 1.1, 'historic'],
    ]);
  });

  it('tolère le BOM et les fins de ligne CRLF', () => {
    const res = parseCgmCsv(`\uFEFF${LIBRE_DMY.replace(/\n/g, '\r\n')}`);
    expect(res.format).toBe('libreview');
    expect(res.readings).toHaveLength(5);
    expect(res.skipped).toBe(2);
  });

  it('détecte un export américain (MDY) avec AM/PM', () => {
    const res = parseCgmCsv(LIBRE_MDY);
    expect(res.format).toBe('libreview');
    expect(res.skipped).toBe(0);
    expect(summary(res.readings)).toEqual([
      [new Date(2026, 9, 11, 0, 5), 0.95, 'historic'],
      [new Date(2026, 9, 11, 8, 15), 1.2, 'historic'],
      [new Date(2026, 9, 11, 12, 10), 1.5, 'historic'],
      [new Date(2026, 9, 25, 13, 30), 1.4, 'historic'],
    ]);
  });

  it('retombe sur DMY pour une date ambiguë et respecte dateOrder forcé', () => {
    expect(parseCgmCsv(LIBRE_AMBIGUOUS).readings[0]?.at).toEqual(new Date(2026, 3, 3, 8, 0));
    expect(parseCgmCsv(LIBRE_AMBIGUOUS, { dateOrder: 'auto' }).readings[0]?.at).toEqual(new Date(2026, 3, 3, 8, 0));
    expect(parseCgmCsv(LIBRE_AMBIGUOUS, { dateOrder: 'MDY' }).readings[0]?.at).toEqual(new Date(2026, 2, 4, 8, 0));
  });

  it('convertit un export mmol/L en g/L', () => {
    const res = parseCgmCsv(LIBRE_MMOL);
    expect(res.unit).toBe('mmol/L');
    expect(summary(res.readings)).toEqual([
      [new Date(2026, 9, 11, 8, 15), 1.21, 'historic'],
      [new Date(2026, 9, 11, 8, 20), 1.3, 'scan'],
      [new Date(2026, 9, 11, 8, 30), 0.9, 'historic'],
      [new Date(2026, 9, 11, 8, 45), 0.79, 'manual'],
    ]);
  });

  it('écarte les doublons exacts du fichier et les compte comme ignorés', () => {
    const row = libreRow('11-10-2026 08:15', '0', { 4: '120' });
    const res = parseCgmCsv([LIBRE_HEADER('mg/dL'), row, row].join('\n'));
    expect(res.readings).toHaveLength(1);
    expect(res.skipped).toBe(1);
  });
});

