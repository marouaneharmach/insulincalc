/** Ligne LibreView à 19 colonnes : seules les cellules nommées sont renseignées. */
function libreRow(ts: string, type: string, cells: Partial<Record<4 | 5 | 11 | 12 | 14, string>> = {}): string {
  const row = Array<string>(19).fill('');
  row[0] = 'FreeStyle LibreLink';
  row[1] = 'ABC123';
  row[2] = ts;
  row[3] = type;
  for (const [idx, value] of Object.entries(cells)) row[Number(idx)] = value;
  return row.join(',');
}

